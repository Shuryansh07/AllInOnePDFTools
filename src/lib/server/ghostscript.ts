import { execFile } from "node:child_process";
import { randomUUID } from "node:crypto";
import { mkdtemp, readFile, rm, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { AppError, ERROR_CODES } from "@/lib/errors/app-error";

/** Maps our preset names to Ghostscript's -dPDFSETTINGS values. */
export const COMPRESSION_PRESETS = {
  low: "/printer",
  recommended: "/ebook",
  extreme: "/screen",
} as const;

export type CompressionPreset = keyof typeof COMPRESSION_PRESETS;

export function isCompressionPreset(value: unknown): value is CompressionPreset {
  return typeof value === "string" && Object.hasOwn(COMPRESSION_PRESETS, value);
}

export function ghostscriptBinary(): string {
  return process.env.GS_PATH ?? (process.platform === "win32" ? "gswin64c" : "gs");
}

/** Arguments are passed as an array (no shell), and paths are generated by us, never by the user. */
export function buildGhostscriptArgs(
  preset: CompressionPreset,
  inputPath: string,
  outputPath: string,
): string[] {
  return [
    "-sDEVICE=pdfwrite",
    "-dCompatibilityLevel=1.4",
    `-dPDFSETTINGS=${COMPRESSION_PRESETS[preset]}`,
    "-dNOPAUSE",
    "-dBATCH",
    "-dQUIET",
    "-dSAFER",
    `-sOutputFile=${outputPath}`,
    inputPath,
  ];
}

export type GhostscriptRunner = (args: string[], timeoutMs: number) => Promise<void>;

const defaultRunner: GhostscriptRunner = (args, timeoutMs) =>
  new Promise((resolve, reject) => {
    // The binary is a system executable, not a project file, so don't trace the project for it.
    execFile(
      /* turbopackIgnore: true */ ghostscriptBinary(),
      args,
      { timeout: timeoutMs, windowsHide: true },
      (error, _stdout, stderr) => {
        if (!error) return resolve();

        const failure = error as NodeJS.ErrnoException & { killed?: boolean };
        if (failure.code === "ENOENT") {
          return reject(
            new AppError(ERROR_CODES.PROCESSING_FAILED, {
              userMessage: "Compression isn't available on this server right now.",
              message: "Ghostscript binary not found. Install it or set GS_PATH.",
              cause: error,
              recoverable: false,
            }),
          );
        }
        if (failure.killed) {
          return reject(new AppError(ERROR_CODES.TIMEOUT, { cause: error }));
        }
        reject(
          new AppError(ERROR_CODES.PROCESSING_FAILED, {
            userMessage: "This PDF couldn't be compressed. It may be damaged or password protected.",
            message: `Ghostscript failed: ${stderr?.toString().slice(0, 500) ?? ""}`,
            cause: error,
          }),
        );
      },
    );
  });

export interface CompressOptions {
  timeoutMs?: number;
  /** Injectable for tests. */
  run?: GhostscriptRunner;
}

export interface CompressResult {
  bytes: Buffer;
  /** True when compression didn't help and the original is returned. */
  unchanged: boolean;
}

/** Compress PDF bytes. Always cleans up its temp directory. */
export async function compressPdf(
  input: Buffer,
  preset: CompressionPreset,
  { timeoutMs = 60_000, run = defaultRunner }: CompressOptions = {},
): Promise<CompressResult> {
  const dir = await mkdtemp(path.join(tmpdir(), "pdfc-"));
  const inputPath = path.join(dir, `${randomUUID()}-in.pdf`);
  const outputPath = path.join(dir, `${randomUUID()}-out.pdf`);

  try {
    await writeFile(inputPath, input);
    await run(buildGhostscriptArgs(preset, inputPath, outputPath), timeoutMs);

    const info = await stat(outputPath).catch(() => null);
    if (!info || info.size === 0) {
      throw new AppError(ERROR_CODES.PROCESSING_FAILED, {
        userMessage: "This PDF couldn't be compressed. It may be damaged or password protected.",
      });
    }

    const output = await readFile(outputPath);
    if (output.length >= input.length) {
      return { bytes: input, unchanged: true };
    }
    return { bytes: output, unchanged: false };
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}
